    #[Computed]
    public function schedule(): array
    {
        return app(RoomSchedule::class)->today($this->room, ttl: $this->night ? self::NIGHT_CACHE_SECONDS : RoomSchedule::FRESH_SECONDS);
    }

    #[Computed]
    public function status(): array
    {
        return app(RoomSchedule::class)->status($this->schedule['events']);

    /**
     * Longest booking that fits right now before the next meeting, in minutes.
     */
    #[Computed]
    public function freeMinutes(): ?int
    {
        if ($this->status['busy']) {
            return 0;
        }
        $until = $this->status['until'];

        return $until ? (int) $this->now()->startOfMinute()->diffInMinutes($until) : null;
    }

    /**
     * Whether people at the screen may book, end or extend (room switch + Microsoft 365 reachable).
     */
    #[Computed]
    public function interactive(): bool
    {
        return $this->room->booking_enabled && $this->schedule['error'] === null;
    }

    /**
     * Extension lengths that fit before the next meeting (and before midnight).
     *
     * @return list<int>
     */
    #[Computed]
    public function extendOptions(): array
    {
        $current = $this->status['current'];
        if (! $current || ! $this->interactive || ! AppSetting::current()->allow_end_extend) {
            return [];
        }

        return array_values(array_filter(self::EXTEND_OPTIONS, function (int $minutes) use ($current): bool {
            $end = $current['end']->addMinutes($minutes);
            if ($end->greaterThan($this->now()->endOfDay())) {
                return false;
            }
            foreach ($this->schedule['events'] as $other) {
                if ($other['id'] !== $current['id'] && $other['start']->lessThan($end) && $other['end']->greaterThan($current['end'])) {
                    return false;
                }
            }

            return true;
        }));
    }

    /**
     * Everything the agenda column needs: meetings laid out for the timeline, free slots and range.
     *
     * @return array{from: CarbonImmutable, to: CarbonImmutable, timed: list<array<string, mixed>>, all_day: list<array<string, mixed>>, free: list<array<string, mixed>>, interactive: bool}
     */
    #[Computed]
    public function agenda(): array
    {
        $schedule = app(RoomSchedule::class);
        $now = $this->now();
        $status = $this->status;
        [$h0, $h1] = $this->settings()->dayHours();

        $dayStart = $now->startOfDay();
        $from = $dayStart->addMinutes((int) round($h0 * 60));
        $to = $dayStart->addMinutes((int) round($h1 * 60));

        $items = [];
        foreach ($this->schedule['events'] as $event) {
            $items[] = [
                'id' => $event['id'],
                'subject' => $this->displaySubject($event),
                'organizer' => $this->displayOrganizer($event),
                'start' => $event['start'],
                'end' => $event['end'],
                'all_day' => $event['is_all_day'],
                'past' => $event['end']->lessThanOrEqualTo($now),
                'current' => $status['current'] && $status['current']['id'] === $event['id'],
                'next' => ! $status['current'] && $status['next'] && $status['next']['id'] === $event['id'],
                'editable' => $this->canChange($event),
                'online' => $event['online'] ?? null,
            ];
        }

        $timed = array_values(array_filter($items, fn ($e) => ! $e['all_day']));

        // The range covers working hours, every meeting of the day and the current time.
        foreach ($timed as $event) {
            $from = $from->min($event['start']);
            $to = $to->max($event['end']);
        }
        $from = $from->min($now)->startOfHour()->max($dayStart);
        $to = $to->max($now);
        $to = ($to->minute || $to->second ? $to->addHour()->startOfHour() : $to)->min($dayStart->addDay());

        $freeFrom = $now->startOfMinute()->max($from);
        // Future free periods only; they are tappable when booking from the screen is allowed.
        $free = $schedule->freeSlots($this->schedule['events'], $freeFrom, $to);

        return [
            'from' => $from,
            'to' => $to,
            'timed' => $schedule->layoutColumns($timed),
            'all_day' => array_values(array_filter($items, fn ($e) => $e['all_day'])),
            'free' => $free,
            'interactive' => $this->interactive,
        ];
    }

    /**
     * Preview of the next working day once today has no meeting left.
     *
     * @return array{date: CarbonImmutable, events: list<array<string, mixed>>}|null
     */
    #[Computed]
    public function upcomingDay(): ?array
    {
        $now = $this->now();
        $remaining = collect($this->schedule['events'])->contains(fn ($e) => $e['end']->greaterThan($now));
        if ($remaining || $this->schedule['error'] !== null) {
            return null;
        }

        $schedule = app(RoomSchedule::class);
        $date = $schedule->nextWorkingDay($now);
        $day = $schedule->day($this->room, $date, ttl: 600);
        if ($day['error'] !== null && ! $day['stale']) {
            return null;
        }

        return [
            'date' => $date,
            'events' => array_map(fn ($e) => [
                'id' => $e['id'],
                'subject' => $this->displaySubject($e),
                'start' => $e['start'],
                'end' => $e['end'],
                'all_day' => $e['is_all_day'],
            ], $day['events']),
        ];
    }

    /**
     * People at the screen may only change meetings booked through the app, while they are not over.
     */
    private function canChange(array $event): bool
    {
        return $this->interactive
            && ! $event['is_all_day']
            && $event['end']->greaterThan($this->now())
            && app(RoomSchedule::class)->isAppBooking($this->room, $event);
    }

    #[Computed]
    public function selectedEvent(): ?array
    {
        if ($this->selectedEventId === null) {
            return null;
        }

        $event = collect($this->schedule['events'])->firstWhere('id', $this->selectedEventId);

        return $event ? $event + [
            'display_subject' => $this->displaySubject($event),
            'display_organizer' => $this->displayOrganizer($event),
            'online' => $event['online'] ?? null,
            'editable' => $this->canChange($event),
        ] : null;
    }

    public function openEvent(string $eventId): void
    {
        $this->selectedEventId = $eventId;
        $this->editingEvent = false;
        unset($this->selectedEvent);

        if ($this->selectedEvent === null) {
            $this->selectedEventId = null;

            return;
        }

        $this->resetValidation();
        $this->modal('kiosk-event')->show();
    }

    public function editEvent(): void
    {
        $event = $this->selectedEvent;
        if (! $event || ! $event['editable']) {
            return;
        }

        $this->subject = $event['subject'];
        $this->start_time = $event['start']->format('H:i');
        $this->end_time = $event['end']->format('H:i');
        $this->editingEvent = true;
        $this->resetValidation();
    }

    public function saveEvent(): void
    {
        $event = $this->selectedEvent;
        if (! $event || ! $event['editable']) {
            return;
        }

        $this->validate([
            'subject' => ['nullable', 'string', 'max:120'],
            'start_time' => ['required', 'date_format:H:i'],
            'end_time' => ['required', 'date_format:H:i', 'after:start_time'],
        ], [
            'end_time.after' => __('The end time must be after the start time.'),
        ]);

        $tz = app(RoomSchedule::class)->timezone();
        $day = $this->now()->toDateString();
        $start = CarbonImmutable::createFromFormat('Y-m-d H:i', $day.' '.$this->start_time, $tz);
        $end = CarbonImmutable::createFromFormat('Y-m-d H:i', $day.' '.$this->end_time, $tz);
        $subject = trim($this->subject) ?: $event['subject'];

        // A meeting already started keeps its start time.
        if ($event['start']->lessThanOrEqualTo($this->now())) {
            $start = $event['start'];
        }

        $done = $this->attempt(function () use ($event, $subject, $start, $end) {
            app(RoomSchedule::class)->reschedule($this->room, $event['id'], $subject, $start, $end);
            Flux::toast(variant: 'success', text: __('Booking updated: :start – :end.', ['start' => fmt_time($start), 'end' => fmt_time($end)]));
        });

        if ($done) {
            $this->closeEvent();
        }
    }

    public function cancelEvent(): void
    {
        $event = $this->selectedEvent;
        if (! $event || ! $event['editable']) {
            return;
        }

        $done = $this->attempt(function () use ($event) {
            app(RoomSchedule::class)->cancel($this->room, $event['id']);
            Flux::toast(variant: 'success', text: __('Booking cancelled.'));
        });

        if ($done) {
            $this->closeEvent();
        }
    }

    public function closeEvent(): void
    {
        $this->modal('kiosk-event')->close();
        $this->selectedEventId = null;
        $this->editingEvent = false;
        $this->reset('subject', 'start_time', 'end_time');
    }

    public function quickBook(int $minutes): void
    {
        if (! in_array($minutes, AppSetting::current()->quickBookDurations(), true)) {
            return;
        }

        $start = $this->now()->startOfMinute();
        $end = $start->addMinutes($minutes);
        if ($this->status['until'] && $end->greaterThan($this->status['until'])) {
            $end = $this->status['until'];
        }

        $this->attempt(function () use ($start, $end) {
            app(RoomSchedule::class)->book($this->room, __('Instant booking'), $start, $end);
            Flux::toast(variant: 'success', heading: __('Room booked'), text: fmt_time($start).' – '.fmt_time($end));
        });
    }

    /**
     * Opens the booking dialog, optionally pre-filled with a free slot tapped on the agenda.
     */
    public function openBookingForm(?string $start = null, ?string $end = null): void
    {
        $default = $this->now()->ceilMinutes(5);
        $valid = fn (?string $t) => is_string($t) && preg_match('/^([01]\d|2[0-3]):[0-5]\d$/', $t) === 1;

        $this->subject = '';
        $this->start_time = $valid($start) ? $start : $default->format('H:i');
        $this->end_time = $valid($end) ? $end : $default->addMinutes(30)->format('H:i');
        $this->resetValidation();
        $this->modal('kiosk-book')->show();
    }

    public function book(): void
    {
        $this->validate([
            'subject' => ['nullable', 'string', 'max:120'],
            'start_time' => ['required', 'date_format:H:i'],
            'end_time' => ['required', 'date_format:H:i', 'after:start_time'],
        ], [
            'end_time.after' => __('The end time must be after the start time.'),
        ]);

        $day = $this->now()->toDateString();
        $tz = app(RoomSchedule::class)->timezone();
        $start = CarbonImmutable::createFromFormat('Y-m-d H:i', $day.' '.$this->start_time, $tz);
        $end = CarbonImmutable::createFromFormat('Y-m-d H:i', $day.' '.$this->end_time, $tz);

        if ($start->lessThan($this->now()->subMinutes(5))) {
            $this->addError('start_time', __('Choose an upcoming time.'));

            return;
        }

        $subject = trim($this->subject) ?: __('On-site booking');
        $done = $this->attempt(function () use ($subject, $start, $end) {
            app(RoomSchedule::class)->book($this->room, $subject, $start, $end);
            Flux::toast(variant: 'success', heading: __('Room booked'), text: fmt_time($start).' – '.fmt_time($end));
        });

        if ($done) {
            $this->reset('subject', 'start_time', 'end_time');
            $this->modal('kiosk-book')->close();
        }
    }

    public function endMeeting(string $eventId): void
    {
        if (! AppSetting::current()->allow_end_extend) {
            return;
        }

        $this->modal('kiosk-end')->close();
        $this->attempt(function () use ($eventId) {
            app(RoomSchedule::class)->endNow($this->room, $eventId);
            Flux::toast(variant: 'success', text: __('The room is free.'));
        });
    }

    public function extendMeeting(string $eventId, int $minutes): void
    {
        if (! AppSetting::current()->allow_end_extend || ! in_array($minutes, self::EXTEND_OPTIONS, true)) {
            return;
        }

        $this->attempt(function () use ($eventId, $minutes) {
            $end = app(RoomSchedule::class)->extend($this->room, $eventId, $minutes);
            Flux::toast(variant: 'success', text: __('Meeting extended until :time.', ['time' => fmt_time($end)]));
        });
    }

    /**
     * Runs a calendar change requested from the screen, with abuse protection and friendly errors.
     */
    private function attempt(callable $action): bool
    {
        if (! $this->room->booking_enabled) {
            return false;
        }

        // Screens are public: cap the number of changes per room to limit abuse.
        $key = 'kiosk-book:'.$this->room->id;
        if (RateLimiter::tooManyAttempts($key, 10)) {
            Flux::toast(variant: 'warning', text: __('Too many bookings in a short time. Try again in a few minutes.'));

            return false;
        }
        RateLimiter::hit($key, 600);

        try {
            $action();
        } catch (BookingException $e) {
            Flux::toast(variant: 'danger', heading: __('Not possible'), text: $e->getMessage());

            return false;
        } finally {
            unset($this->schedule, $this->status, $this->freeMinutes, $this->extendOptions, $this->agenda, $this->upcomingDay, $this->selectedEvent);
        }

        return true;
    }

    public function displaySubject(array $event): string
    {
        return app(RoomSchedule::class)->displaySubject($this->room, $event);
    }

    public function displayOrganizer(array $event): ?string
    {
        return app(RoomSchedule::class)->displayOrganizer($this->room, $event);
    }

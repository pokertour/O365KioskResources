    public function mount(Room $room, string $token): void
    {
        $screen = $room->screenFor($token);
        abort_unless($screen !== null, 404);

        $this->room = $room;
        $this->screenId = $screen->id;
        $this->tokenHash = $screen->token_hash;
        $this->brandingVersion = $this->screenVersion();
        View::share('kioskRoom', $room);
        View::share('kioskScreen', $screen);
        $screen->markSeen();
    }

    public function hydrate(): void
    {
        $screen = $this->screen;
        if (! $screen || $screen->room_id !== $this->room->id || ! hash_equals($screen->token_hash, $this->tokenHash)) {
            // Screen removed or its link regenerated by an admin: reloading lands on the 404 page.
            $this->js('window.location.reload()');
            $this->skipRender();

            return;
        }

        $screen->markSeen();

        // Look or settings changed by an admin (logo, colours, language, time zone…): reload.
        if ($this->screenVersion() !== $this->brandingVersion) {
            $this->js('window.location.reload()');
        }
    }

    private function screenVersion(): string
    {
        return BrandingSetting::current()->version().'-'.AppSetting::current()->updated_at?->getTimestamp()
            .'-'.$this->room->updated_at?->getTimestamp().'-'.$this->screen?->updated_at?->getTimestamp();
    }

    #[Computed]
    public function screen(): ?Screen
    {
        return Screen::query()->find($this->screenId);
    }

    /**
     * Global settings, then this room's overrides, then this screen's overrides.
     */
    public function settings(): AppSetting
    {
        return $this->screen ? AppSetting::forScreen($this->screen) : AppSetting::forRoom($this->room);
    }

    /**
     * Sent once by the browser: viewport and device, shown in the admin supervision panel.
     */
    public function reportScreen(int $width, int $height, float $ratio = 1): void
    {
        $agent = (string) request()->userAgent();
        $device = match (true) {
            str_contains($agent, 'iPad') => 'iPad',
            str_contains($agent, 'iPhone') => 'iPhone',
            str_contains($agent, 'Android') => 'Android',
            str_contains($agent, 'CrOS') => 'ChromeOS',
            str_contains($agent, 'Windows') => 'Windows',
            str_contains($agent, 'Macintosh') => 'macOS',
            str_contains($agent, 'Linux') => 'Linux',
            default => __('Unknown'),
        };
        $browser = match (true) {
            str_contains($agent, 'Edg/') => 'Edge',
            str_contains($agent, 'Chrome/') => 'Chrome',
            str_contains($agent, 'Firefox/') => 'Firefox',
            str_contains($agent, 'Safari/') => 'Safari',
            default => null,
        };

        $this->screen?->markSeen([
            'width' => max(0, min($width, 20000)),
            'height' => max(0, min($height, 20000)),
            'ratio' => round(max(0.5, min($ratio, 8)), 2),
            'device' => $browser ? "{$device} · {$browser}" : $device,
            'agent' => mb_substr($agent, 0, 255),
        ]);
        $this->skipRender();
    }


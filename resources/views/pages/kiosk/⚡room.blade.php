    public function reportIssue(): void
    {
        $this->validate([
            'issueCategory' => ['required', Rule::in(array_keys($this->issueCategories))],
            'issueMessage' => ['nullable', 'string', 'max:500'],
        ], [
            'issueCategory.required' => __('Choose what is wrong.'),
        ]);

        $key = 'kiosk-report:'.$this->room->id;
        if (RateLimiter::tooManyAttempts($key, 3)) {
            Flux::toast(variant: 'warning', text: __('Several issues were already reported. Thank you!'));
            $this->modal('kiosk-issue')->close();

            return;
        }
        RateLimiter::hit($key, 600);

        $issue = IssueReport::query()->create([
            'room_id' => $this->room->id,
            'category' => $this->issueCategory,
            'message' => trim($this->issueMessage) ?: null,
        ]);
        $label = IssueReport::categoryLabel($issue->category);
        ActivityLog::record('issue.reported', $this->room, $label);

        app(AdminNotifier::class)->send(
            __('Issue reported in :room', ['room' => $this->room->name]),
            $label.($issue->message ? ' — '.$issue->message : ''),
            route('admin.rooms.show', ['room' => $this->room, 'tab' => 'activity']),
            __('Open the room'),
        );

        $this->modal('kiosk-issue')->close();
        $this->reset('issueCategory', 'issueMessage');
        Flux::toast(variant: 'success', heading: __('Thank you!'), text: __('The issue has been sent to the administrators.'));
    }

    public function now(): CarbonImmutable

    /**
     * QR code (SVG) to the mobile view of this room. The link is signed and short-lived, and
     * regenerated regularly, so it cannot be reused long after leaving the room.
     */
    #[Computed]
    public function qrCode(): ?string
    {
        if (! $this->settings()->show_qr_code) {
            return null;
        }

        return cache()->remember("room-qr:{$this->room->id}:".app()->getLocale(), now()->addMinutes(10), function (): string {
            $url = URL::temporarySignedRoute('room.mobile', now()->addMinutes(30), ['room' => $this->room]);
            $renderer = new \BaconQrCode\Renderer\ImageRenderer(
                new \BaconQrCode\Renderer\RendererStyle\RendererStyle(240, 1),
                new \BaconQrCode\Renderer\Image\SvgImageBackEnd,
            );

            return (new \BaconQrCode\Writer($renderer))->writeString($url);
        });
    }

    /**
     * @return array<string, string> category => label
     */
    #[Computed]
    public function issueCategories(): array
    {
        $categories = [];
        foreach ($this->room->equipmentList() as $key) {
            $categories[$key] = Room::equipmentLabel($key);
        }
        foreach (IssueReport::GENERAL_CATEGORIES as $key) {
            $categories[$key] = IssueReport::categoryLabel($key);
        }

        return $categories;
